import numpy as np
print("---------------------------------3X3 matrix--(Give scaler)---------------------------------------")
a = np.array([
    [[1, 2],
     [3, 4]],

    [[5, 6],
     [7, 8]]
])
b = np.array([
    [[10, 20],
     [30, 40]],

    [[50, 60],
     [70, 80]]
])
