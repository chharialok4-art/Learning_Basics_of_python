import numpy as np;
print("--------------------------------1D Array-----------------------------------------")
a = np.array([0, 0, 3, 4, 0, 5, 0, 0]);
print(a[a!=0]);
print("--------------------------------2D Array-----------------------------------------")
b=np.array([[0,0,100,200,300,0,0],[0,0,101,202,303,0,0]]);
print("Original:\n",b);
print("Trimmed:\n",b[b!=0].reshape(2,3));
print("--------------------------------2D Array with nonzero function-----------------------------------------")
print(b[np.nonzero(b)].reshape(2,3));
